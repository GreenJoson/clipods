const translations: Record<Locale, Record<TranslationKey, string>> = { zh, en };

const formatMessage = (
  template: string,
  params?: Record<string, string | number>
): string => {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/gu, (match, key) => {
    const value = params[key];
    return value === undefined ? match : String(value);
  });
};

export const translate = (
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>
): string => formatMessage(translations[locale][key] ?? zh[key], params);

interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

const readInitialLocale = (): Locale => {
  if (typeof window === "undefined") {
    return "zh";
  }
  const saved = window.localStorage.getItem("clipods.locale");
  if (saved === "zh" || saved === "en") {
    return saved;
  }
  return "zh";
};

export const LocaleProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocale] = useState<Locale>(readInitialLocale);

  useEffect(() => {
    window.localStorage.setItem("clipods.locale", locale);
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale }), [locale]);

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
};

export const useI18n = () => {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useI18n must be used within LocaleProvider");
  }
  const t = useMemo(
    () =>
      (key: TranslationKey, params?: Record<string, string | number>) =>
        translate(context.locale, key, params),
    [context.locale]
  );
  return { locale: context.locale, setLocale: context.setLocale, t };
};
